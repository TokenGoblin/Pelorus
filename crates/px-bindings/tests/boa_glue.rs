//! The Boa glue emitter. The crate has no Boa dependency (ADR 040), so these
//! tests check the text: determinism, the host-trait names it calls, the
//! shape of the conversions, and that every gap is reported in `UNSUPPORTED`.
//! The emitted glue was also compiled and run against `boa_engine =0.22.0`
//! outside the workspace; see the STATUS in `docs/phase-11-bindings.md`.

macro_rules! fail {
    ($($t:tt)*) => {
        ::std::panic::panic_any(format!($($t)*))
    };
}

use px_bindings::emit::{BoaGlueEmitter, Emitter, RustHostEmitter};
use px_bindings::resolve::BuildOptions;
use std::path::PathBuf;

fn gen_both(sources: &[(String, String)], strict: bool) -> (String, String) {
    let emitters: [&dyn Emitter; 2] = [&RustHostEmitter, &BoaGlueEmitter];
    let out = px_bindings::generate(
        sources,
        BuildOptions {
            require_exposed: strict,
        },
        &emitters,
    )
    .unwrap_or_else(|e| fail!("{e:#?}"));
    let find = |p: &str| {
        out.iter()
            .find(|o| o.path == p)
            .map(|o| o.contents.clone())
            .unwrap_or_else(|| fail!("no {p}"))
    };
    (find("host.rs"), find("boa.rs"))
}

fn one(idl: &str) -> (String, String) {
    gen_both(&[("t.idl".to_owned(), idl.to_owned())], false)
}

fn subset() -> Vec<(String, String)> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("idl");
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| fail!("{e}"))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "idl"))
        .collect();
    files.sort();
    files
        .iter()
        .map(|p| {
            (
                p.file_name()
                    .map_or_else(String::new, |n| n.to_string_lossy().into_owned()),
                std::fs::read_to_string(p).unwrap_or_else(|e| fail!("{e}")),
            )
        })
        .collect()
}

/// Text of `pub trait <name> ... { ... }` in `host`.
fn trait_body<'a>(host: &'a str, name: &str) -> &'a str {
    let head = format!("pub trait {name}");
    let start = host.find(&head).unwrap_or_else(|| fail!("no trait {name}"));
    let rest = host.get(start..).unwrap_or_default();
    let end = rest.find("\n}\n").unwrap_or(rest.len());
    rest.get(..end).unwrap_or_default()
}

#[test]
fn output_is_deterministic_and_has_no_unsafe() {
    let s = subset();
    let (_, a) = gen_both(&s, true);
    let (_, b) = gen_both(&s, true);
    assert_eq!(a, b);
    assert!(!a.contains("unsafe"), "the glue must not need unsafe");
    assert!(a.starts_with("// @generated by px-bindings"));
}

#[test]
fn every_host_call_names_a_method_of_that_trait() {
    let (host, boa) = gen_both(&subset(), true);
    let mut calls = 0;
    for line in boa.lines() {
        let mut rest = line;
        while let Some(at) = rest.find("<H as ") {
            let after = rest.get(at + 6..).unwrap_or_default();
            let Some((tr, tail)) = after.split_once(">::") else {
                break;
            };
            let name = tail.split('(').next().unwrap_or_default();
            let body = trait_body(&host, tr);
            let sig = format!("fn {name}(&mut self");
            assert!(body.contains(&sig), "{tr} has no `{name}` in:\n{line}");
            calls += 1;
            rest = tail;
        }
    }
    // Attributes, operations and constructors of the committed subset.
    assert!(calls > 80, "only {calls} host calls found");
}

#[test]
fn subset_gaps_are_exactly_the_reported_ones() {
    let (_, boa) = gen_both(&subset(), true);
    let list: Vec<&str> = boa
        .lines()
        .skip_while(|l| !l.starts_with("pub static UNSUPPORTED"))
        .skip(1)
        .take_while(|l| *l != "];")
        .collect();
    // Dictionaries, callback interfaces and unions are not converted yet;
    // iterable/maplike/setlike are not bound. Changing this list is a
    // deliberate act: update STATUS in docs/phase-11-bindings.md with it.
    assert_eq!(list.len(), 20, "{list:#?}");
    let kinds = |needle: &str| list.iter().filter(|l| l.contains(needle)).count();
    assert_eq!(kinds("conversion for union"), 14);
    assert_eq!(kinds("conversion for dictionary"), 2);
    assert_eq!(kinds("conversion for callback interface"), 2);
    assert_eq!(kinds("collection bindings"), 2);
}

#[test]
fn parents_are_installed_before_children() {
    let (_, boa) = gen_both(&subset(), true);
    let at = |s: &str| {
        boa.find(&format!("    // {s}\n"))
            .unwrap_or_else(|| fail!("no {s}"))
    };
    assert!(at("EventTarget") < at("Node"));
    assert!(at("Node") < at("Element"));
    assert!(at("Node") < at("CharacterData"));
    assert!(at("CharacterData") < at("Text"));
}

#[test]
fn integer_conversions_carry_their_mode() {
    let (_, boa) = one(
        "interface I { undefined f([EnforceRange] octet a, [Clamp] long b, unsigned short c, long long d); };",
    );
    assert!(boa.contains("conv_int(v, ctx, 8, false, ConvMode::EnforceRange)? as u8"));
    assert!(boa.contains("conv_int(v, ctx, 32, true, ConvMode::Clamp)? as i32"));
    assert!(boa.contains("conv_int(v, ctx, 16, false, ConvMode::Wrap)? as u16"));
    assert!(boa.contains("conv_int(v, ctx, 64, true, ConvMode::Wrap)? as i64"));
    assert!(boa.contains("if args.len() < 4"), "required-argument check");
}

#[test]
fn optional_arguments_use_the_idl_default() {
    let (_, boa) = one(
        r#"interface I { DOMString f(DOMString a, optional DOMString b = "z", optional long c); };"#,
    );
    assert!(boa.contains("_ => ::std::string::String::from(\"z\")"));
    assert!(boa.contains("Some(v) if !v.is_undefined() => Some("));
    assert!(boa.contains("if args.len() < 1"));
}

#[test]
fn nullable_and_enum_round_trip() {
    let (_, boa) = one(
        r#"enum E { "a", "b" }; interface I { attribute E e; I? other(); attribute DOMString? s; };"#,
    );
    assert!(boa.contains("E::from_idl_str("));
    assert!(boa.contains("as_idl_str()"));
    assert!(boa.contains("None => JsValue::null()"));
    assert!(boa.contains("is_null_or_undefined()"));
}

#[test]
fn overloads_with_distinct_arity_dispatch_on_count() {
    let (host, boa) = one("interface I { undefined f(); undefined f(long a); };");
    assert!(host.contains("fn f_1(&mut self"));
    assert!(boa.contains("<H as IHost>::f_1("));
    assert!(boa.contains("i_f_o0::<H>(this, args, ctx)"));
    assert!(boa.contains("i_f_o1::<H>(this, args, ctx)"));
}

#[test]
fn overloads_that_need_type_resolution_are_reported_not_guessed() {
    let (_, boa) = one("interface I { undefined f(long a); undefined f(DOMString a); };");
    assert!(boa.contains("I.f: overloads share an argument count"));
    assert!(!boa.contains("def_method(ctx, &o_i, \"f\""));
}

#[test]
fn special_operations_and_collections_are_reported() {
    let (_, boa) = one("interface I { getter DOMString (unsigned long i); iterable<DOMString>; };");
    assert!(boa.contains("I.special operation"));
    assert!(boa.contains("I.iterable/maplike/setlike"));
}

#[test]
fn statics_namespaces_and_constants() {
    let (_, boa) = one(
        "interface I { static long make(); const unsigned short K = 3; }; namespace N { long g(); };",
    );
    assert!(boa.contains("def_method(ctx, &o_i_ctor, \"make\""));
    assert!(boa.contains("def_const(ctx, &o_i_ctor, \"K\", JsValue::from(3_f64))"));
    assert!(boa.contains("def_const(ctx, &o_i, \"K\""));
    assert!(boa.contains("let o_n = ObjectInitializer::new(ctx).build();"));
    assert!(boa.contains("def_method(ctx, &o_n, \"g\""));
}

#[test]
fn inheritance_sets_prototype_and_constructor_parents() {
    let (_, boa) = one("interface A {}; interface B : A {};");
    assert!(boa.contains("make_proto(ctx, protos.get(\"A\").cloned())"));
    assert!(boa.contains("ctors.get(\"A\").cloned())"));
    assert!(boa.contains("Interface { name: \"B\", chain: &[\"B\", \"A\"] }"));
}
