//! `cargo xtask update-psl` -- refresh the Public Suffix List and its version
//! file, together. Port of `ci/update-psl.sh`.
//!
//! Together is the whole point. The version file is what makes "stale" a
//! question with an answer, and a list refreshed without it -- or a version
//! edited to match a list nobody re-fetched -- is worse than an old list,
//! because it reads as though someone checked.
//!
//! ```text
//! cargo xtask update-psl                    fetch, write both files, report what changed
//! cargo xtask update-psl --check            report whether upstream differs; change nothing
//! cargo xtask update-psl --from-file <f>    use <f> instead of fetching (offline / testing)
//! ```
//!
//! Not run by any gate. The gate asserts that the two files agree with each
//! other and that the fetch date is inside a year; it does not reach the
//! network, because a gate that depends on publicsuffix.org being up is a gate
//! that goes red for reasons nobody here controls.
//!
//! The fetch is `curl` as a child process, exactly as the script did.

use crate::Gate;
use crate::clock;
use crate::proc;
use crate::sha256;
use std::path::{Path, PathBuf};

pub const SOURCE: &str = "https://publicsuffix.org/list/public_suffix_list.dat";
const LIST: &str = "data/public_suffix_list.dat";
const VERSION: &str = "data/public_suffix_list.version";

/// A truncated download that still exits zero would otherwise be written over
/// a good list, and a short list is a wide partition boundary -- the failure
/// this file exists to prevent. The real list is ~16k lines; 5000 is a floor
/// well below it and well above any plausible error page.
const MIN_LINES: usize = 5000;

#[derive(Debug, PartialEq, Eq)]
pub struct Opts {
    pub check: bool,
    pub from_file: Option<PathBuf>,
}

pub fn parse_args(args: &[String]) -> Result<Opts, String> {
    let mut o = Opts {
        check: false,
        from_file: None,
    };
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--check" => o.check = true,
            "--from-file" => {
                let v = it.next().ok_or("--from-file needs a path")?;
                o.from_file = Some(PathBuf::from(v));
            }
            other => return Err(format!("unknown argument `{other}`")),
        }
    }
    Ok(o)
}

/// `curl -fsSL -H "User-Agent: build-data-fetch" <url>`, body on stdout.
///
/// The User-Agent deliberately does not name the product. The brand gate
/// confines the product name to px-brand, docs/, packaging/, README and the
/// workspace manifest, and a build tool is none of those.
pub fn fetch(g: &mut Gate, url: &str) -> Option<Vec<u8>> {
    g.info(format!("fetching {url}"));
    match proc::capture(
        "curl",
        &["-fsSL", "-H", "User-Agent: build-data-fetch", url],
        None,
    ) {
        Ok(b) => Some(b),
        Err(e) if e.starts_with("cannot run") => {
            g.fail("curl is not on PATH");
            None
        }
        Err(e) => {
            g.fail("could not fetch the list");
            g.detail(e);
            None
        }
    }
}

/// Is this plausibly the list? `wc -l` counts newline bytes.
pub fn validate(list: &[u8]) -> Result<(), String> {
    let lines = list.iter().filter(|b| **b == b'\n').count();
    if lines < MIN_LINES {
        return Err(format!(
            "the fetched list has only {lines} lines; refusing to install it"
        ));
    }
    // grep -q "^// ===BEGIN ICANN DOMAINS===": at the start of some line.
    let marker = b"// ===BEGIN ICANN DOMAINS===";
    let has = list.split(|b| *b == b'\n').any(|l| l.starts_with(marker));
    if !has {
        return Err("the fetched file has no ICANN section marker; it is not the list".into());
    }
    Ok(())
}

/// The version file, byte for byte what the script's heredoc wrote.
pub fn version_text(sha: &str, fetched: &str, source: &str) -> String {
    format!(
        "\
# Public Suffix List version.
#
# The PSL carries no version number of its own, so this file is the version:
# the SHA-256 of the list as fetched, and the date it was fetched. Both are
# asserted by crates/px-net/tests/psl.rs.
#
# Why this file exists at all. Partitioning is keyed by eTLD+1 (invariant 2),
# so a stale list does not degrade privacy gently - it draws the security
# boundary in the wrong place, and nothing observable breaks. A suffix added
# upstream and missing here means two sites this browser believes are one.
# There is no symptom to notice, which is why staleness has to be measurable
# rather than felt.
#
# Generated by `cargo xtask update-psl`. Editing either file by hand defeats
# the assertion that they describe each other.

sha256 = \"{sha}\"
fetched = \"{fetched}\"
source = \"{source}\"
"
    )
}

#[derive(Debug, PartialEq, Eq)]
pub enum Action {
    /// `--check` and the shipped list matches.
    CheckMatches,
    /// `--check` and it does not.
    CheckDiffers,
    /// Not `--check`, nothing to do.
    AlreadyCurrent,
    Install,
}

pub fn decide(check: bool, new_sha: &str, old_sha: &str) -> Action {
    match (check, new_sha == old_sha) {
        (true, true) => Action::CheckMatches,
        (true, false) => Action::CheckDiffers,
        (false, true) => Action::AlreadyCurrent,
        (false, false) => Action::Install,
    }
}

pub fn run(g: &mut Gate, root: &Path, args: &[String]) {
    let opts = match parse_args(args) {
        Ok(o) => o,
        Err(e) => {
            g.fail(e);
            return;
        }
    };
    let list = match &opts.from_file {
        Some(p) => match std::fs::read(p) {
            Ok(b) => b,
            Err(e) => {
                g.fail(format!("cannot read {}: {e}", p.display()));
                return;
            }
        },
        None => match fetch(g, SOURCE) {
            Some(b) => b,
            None => return,
        },
    };
    if let Err(e) = validate(&list) {
        g.fail(e);
        return;
    }

    let new_sha = sha256::hex_of(&list);
    let list_path = root.join(LIST);
    let old_sha = std::fs::read(&list_path)
        .map(|b| sha256::hex_of(&b))
        .unwrap_or_default();

    match decide(opts.check, &new_sha, &old_sha) {
        Action::CheckMatches => g.ok("the shipped list matches upstream"),
        Action::CheckDiffers => {
            g.fail("upstream differs from the shipped list; run `cargo xtask update-psl`")
        }
        Action::AlreadyCurrent => g.ok(format!("already current ({new_sha})")),
        Action::Install => {
            let fetched = clock::today_utc();
            if let Err(e) = std::fs::write(&list_path, &list) {
                g.fail(format!("cannot write {LIST}: {e}"));
                return;
            }
            if let Err(e) =
                std::fs::write(root.join(VERSION), version_text(&new_sha, &fetched, SOURCE))
            {
                g.fail(format!("cannot write {VERSION}: {e}"));
                return;
            }
            g.ok("updated");
            g.info(format!("  was {old_sha}"));
            g.info(format!("  now {new_sha}"));
            g.info(format!("  fetched {fetched}"));
            g.info("run the gate before committing: cargo test -p px-net --test psl");
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testutil::Fixture;

    fn fake_list(lines: usize) -> String {
        let mut s = String::from("// ===BEGIN ICANN DOMAINS===\n");
        for i in 0..lines {
            s.push_str(&format!("s{i}.example\n"));
        }
        s
    }

    #[test]
    fn validate_rejects_short_and_unmarked() {
        assert!(validate(fake_list(6000).as_bytes()).is_ok());
        let short = validate(fake_list(10).as_bytes()).unwrap_err();
        assert!(short.contains("only 11 lines"), "{short}");
        let unmarked = "x\n".repeat(6000);
        assert!(validate(unmarked.as_bytes()).unwrap_err().contains("ICANN"));
        // The marker must start a line.
        let indented = format!(" // ===BEGIN ICANN DOMAINS===\n{}", "x\n".repeat(6000));
        assert!(validate(indented.as_bytes()).is_err());
        assert!(validate(b"").is_err());
    }

    #[test]
    fn decisions() {
        assert_eq!(decide(true, "a", "a"), Action::CheckMatches);
        assert_eq!(decide(true, "a", "b"), Action::CheckDiffers);
        assert_eq!(decide(false, "a", "a"), Action::AlreadyCurrent);
        assert_eq!(decide(false, "a", ""), Action::Install);
    }

    #[test]
    fn args() {
        assert_eq!(
            parse_args(&["--check".into()]).unwrap(),
            Opts {
                check: true,
                from_file: None
            }
        );
        assert!(parse_args(&["--from-file".into()]).is_err());
        assert!(parse_args(&["--bogus".into()]).is_err());
    }

    #[test]
    fn version_text_layout() {
        let t = version_text("abc", "2026-01-02", SOURCE);
        assert!(t.starts_with("# Public Suffix List version.\n#\n"));
        assert!(t.ends_with(
            "\nsha256 = \"abc\"\nfetched = \"2026-01-02\"\nsource = \"https://publicsuffix.org/list/public_suffix_list.dat\"\n"
        ));
        assert!(t.contains("describe each other.\n\nsha256 = "));
    }

    #[test]
    fn install_check_and_idempotence() {
        let f = Fixture::new("psl");
        f.write("data/public_suffix_list.dat", "old\n");
        let src = f.path().join("new.dat");
        std::fs::write(&src, fake_list(6000)).unwrap();
        let a = |extra: &[&str]| -> Vec<String> {
            let mut v: Vec<String> = vec!["--from-file".into(), src.display().to_string()];
            v.extend(extra.iter().map(|s| s.to_string()));
            v
        };

        // --check against a different shipped list fails and changes nothing.
        let mut g = Gate::new("t");
        run(&mut g, f.path(), &a(&["--check"]));
        assert_eq!(g.fail_count(), 1);
        assert_eq!(
            std::fs::read_to_string(f.path().join(LIST)).unwrap(),
            "old\n"
        );
        assert!(!f.path().join(VERSION).exists());

        // Install writes both files.
        let mut g = Gate::new("t");
        run(&mut g, f.path(), &a(&[]));
        assert!(g.passed());
        let sha = sha256::hex_of(fake_list(6000).as_bytes());
        let ver = std::fs::read_to_string(f.path().join(VERSION)).unwrap();
        assert!(ver.contains(&format!("sha256 = \"{sha}\"")));
        assert_eq!(
            std::fs::read(f.path().join(LIST)).unwrap(),
            fake_list(6000).into_bytes()
        );

        // Now --check passes, and a rerun leaves the version file untouched.
        let mut g = Gate::new("t");
        run(&mut g, f.path(), &a(&["--check"]));
        assert!(g.passed());
        std::fs::write(f.path().join(VERSION), "sentinel").unwrap();
        let mut g = Gate::new("t");
        run(&mut g, f.path(), &a(&[]));
        assert!(g.passed());
        assert_eq!(
            std::fs::read_to_string(f.path().join(VERSION)).unwrap(),
            "sentinel"
        );
    }

    #[test]
    fn invalid_input_is_refused_and_nothing_is_written() {
        let f = Fixture::new("psl-bad");
        f.write("data/public_suffix_list.dat", "old\n");
        f.write("bad.dat", "<html>error</html>\n");
        let mut g = Gate::new("t");
        run(
            &mut g,
            f.path(),
            &[
                "--from-file".into(),
                f.path().join("bad.dat").display().to_string(),
            ],
        );
        assert_eq!(g.fail_count(), 1);
        assert_eq!(
            std::fs::read_to_string(f.path().join(LIST)).unwrap(),
            "old\n"
        );
    }
}
