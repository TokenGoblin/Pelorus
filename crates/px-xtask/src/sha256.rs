//! SHA-256 (FIPS 180-4), by hand, std only.
//!
//! The reproducibility gate (`build-and-hash`) must print the same digest
//! `sha256sum` would, and ADR 032 forbids a dependency to get it. The tests
//! below pin it to the FIPS test vectors and, where `sha256sum` exists, to the
//! real tool on real files.
//!
//! This is an integrity fingerprint for comparing two builds of our own source,
//! not a security primitive; it is nonetheless the textbook algorithm, with no
//! shortcuts.

